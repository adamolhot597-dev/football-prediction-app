st.sidebar.header("🎯 قائمة التحكم")
app_mode = st.sidebar.radio(
    "اختر القسم:",
    [
        "📥 رفع الأرشيف والتعلم التلقائي", 
        "🧠 فحص البرنامج الجديد واكتشاف النمط",
        "⚙️ ربط API النتائج (API-Football)"
    ]
)

